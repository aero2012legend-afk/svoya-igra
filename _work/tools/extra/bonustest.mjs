import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8080/index.html', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(2500);
await p.keyboard.press('Space'); await p.waitForTimeout(800);
await p.click('[data-act=add]'); await p.waitForTimeout(250); await p.keyboard.press('Control+A'); await p.keyboard.type('Вася'); await p.keyboard.press('Enter'); await p.waitForTimeout(300);
await p.click('[data-act=start]'); await p.waitForTimeout(40000);
const c = await p.evaluate(() => { const g = window.GAME; for (const [t, th] of g.rounds[0].themes.entries()) for (const [i, q] of th.questions.entries()) if (q.type === 'bonus' && q.q) return { t, i, name: th.name, price: q.price }; });
console.log('bonus cell', JSON.stringify(c));
await p.click(`.cell[data-t="${c.t}"][data-i="${c.i}"]`); await p.waitForTimeout(6000);
console.log('stage', await p.evaluate(() => window.__svi.G.q.stage + ' ' + (window.__svi.G.q.con && window.__svi.G.q.con.step)));
console.log('button', await p.evaluate(() => [...document.querySelectorAll('#stage .hostbar button')].map(b => b.textContent).join(' | ')));
await p.keyboard.press('ArrowRight'); await p.waitForTimeout(3500);
const st = await p.evaluate(() => ({ stage: window.__svi.G.q.stage, type: window.__svi.G.q.type, text: (document.querySelector('#stage .qtext') || {}).textContent }));
console.log('after', JSON.stringify(st).slice(0, 200));
await p.screenshot({ path: 'bonus_q.jpg', quality: 55, type: 'jpeg' });
console.log('ОШИБКИ:', errs.length ? errs.join('\n') : 'нет'); await b.close();
